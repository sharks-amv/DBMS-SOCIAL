-- ============================ TABLES ============================

CREATE TABLE app_user (
    user_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    email          VARCHAR(150) UNIQUE NOT NULL,
    password       VARCHAR(255) DEFAULT 'password123',
    date_joined    TIMESTAMPTZ DEFAULT NOW(),
    date_of_birth  DATE DEFAULT '1998-01-01',
    bio            VARCHAR(500)
);

CREATE TABLE profile (
    profile_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT REFERENCES app_user(user_id) ON DELETE CASCADE UNIQUE,
    profile_picture  VARCHAR(500),
    location         VARCHAR(150),
    website          VARCHAR(255)
);

CREATE TABLE post (
    post_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT REFERENCES app_user(user_id) ON DELETE CASCADE NOT NULL,
    content      VARCHAR(2000) NOT NULL,
    created_at   TIMESTAMPTZ DEFAULT NOW(),
    visibility   VARCHAR(10) DEFAULT 'public',
    post_type    VARCHAR(20) DEFAULT 'status'
);

CREATE TABLE post_comment (
    comment_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id       BIGINT REFERENCES post(post_id) ON DELETE CASCADE NOT NULL,
    user_id       BIGINT REFERENCES app_user(user_id) ON DELETE CASCADE NOT NULL,
    comment_text  VARCHAR(1000) NOT NULL,
    created_at    TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE post_like (
    post_id   BIGINT REFERENCES post(post_id) ON DELETE CASCADE NOT NULL,
    user_id   BIGINT REFERENCES app_user(user_id) ON DELETE CASCADE NOT NULL,
    liked_at  TIMESTAMPTZ DEFAULT NOW(),
    PRIMARY KEY (post_id, user_id)
);

CREATE TABLE user_follow (
    follower_id   BIGINT REFERENCES app_user(user_id) ON DELETE CASCADE NOT NULL,
    following_id  BIGINT REFERENCES app_user(user_id) ON DELETE CASCADE NOT NULL,
    followed_at   TIMESTAMPTZ DEFAULT NOW(),
    PRIMARY KEY (follower_id, following_id)
);

CREATE TABLE hashtag (
    hashtag_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hashtag_name  VARCHAR(100) UNIQUE NOT NULL
);

CREATE TABLE post_hashtag (
    post_id     BIGINT REFERENCES post(post_id) ON DELETE CASCADE NOT NULL,
    hashtag_id  BIGINT REFERENCES hashtag(hashtag_id) ON DELETE CASCADE NOT NULL,
    PRIMARY KEY (post_id, hashtag_id)
);

CREATE TABLE media (
    media_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id      BIGINT REFERENCES post(post_id) ON DELETE CASCADE NOT NULL,
    media_url    VARCHAR(1000) NOT NULL,
    media_type   VARCHAR(20) DEFAULT 'image',
    uploaded_at  TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE social_platform (
    platform_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform_name  VARCHAR(100) UNIQUE NOT NULL,
    platform_url   VARCHAR(255)
);

CREATE TABLE social_account (
    account_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT REFERENCES app_user(user_id) ON DELETE CASCADE NOT NULL,
    platform_id     BIGINT REFERENCES social_platform(platform_id) ON DELETE CASCADE NOT NULL,
    username        VARCHAR(100),
    account_status  VARCHAR(20) DEFAULT 'active',
    connected_at    TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE message (
    message_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id     BIGINT REFERENCES app_user(user_id) ON DELETE CASCADE NOT NULL,
    receiver_id   BIGINT REFERENCES app_user(user_id) ON DELETE CASCADE NOT NULL,
    message_text  VARCHAR(2000) NOT NULL,
    sent_at       TIMESTAMPTZ DEFAULT NOW(),
    is_read       CHAR(1) DEFAULT 'N'
);

CREATE TABLE notification (
    notification_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT REFERENCES app_user(user_id) ON DELETE CASCADE NOT NULL,
    notification_type  VARCHAR(20) NOT NULL,
    notification_text  VARCHAR(500) NOT NULL,
    created_at         TIMESTAMPTZ DEFAULT NOW(),
    is_read            CHAR(1) DEFAULT 'N'
);

-- ============================ TRIGGER FUNCTIONS ============================

-- 1. Notify follow
CREATE OR REPLACE FUNCTION fn_notify_follow()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    INSERT INTO notification (user_id, notification_type, notification_text)
    VALUES (NEW.following_id, 'FOLLOW', 'You have a new follower');
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_notify_follow
AFTER INSERT ON user_follow
FOR EACH ROW EXECUTE FUNCTION fn_notify_follow();

-- 2. Notify like
CREATE OR REPLACE FUNCTION fn_notify_like()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_owner_id BIGINT;
BEGIN
    SELECT user_id INTO v_owner_id FROM post WHERE post_id = NEW.post_id;
    IF v_owner_id IS NOT NULL AND v_owner_id <> NEW.user_id THEN
        INSERT INTO notification (user_id, notification_type, notification_text)
        VALUES (v_owner_id, 'LIKE', 'Someone liked your post');
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_notify_like
AFTER INSERT ON post_like
FOR EACH ROW EXECUTE FUNCTION fn_notify_like();

